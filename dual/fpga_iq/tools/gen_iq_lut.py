#!/usr/bin/env python3
"""Generate src/iq_phase_lut.v: 8-bit IQ word -> 10-bit phase + cell class.

C5VRX streams the ADC as signed 4-bit nibbles (two's complement, truncated),
Q on bits 3:0 and I on bits 7:4.  A nibble k stands for the ADC interval
[k, k+1) of its step, so the cell centre is k + 0.5; the angle is taken from
the centres (2k+1), which keeps the lattice symmetric about the origin.

Class bits:
  bit 0 origin: both nibbles in {-1, 0}, the four cells touching the origin
                (the phase there is mostly noise; C5VRX-5 U85Q gives them
                half weight)
  bit 1 rail:   either nibble is -8 or +7 (the slice is full scale)
"""
import math
import os

def s4(v):
    return v - 16 if v & 8 else v

rows = []
for w in range(256):
    q = s4(w & 15)
    i = s4(w >> 4)
    ci, cq = 2 * i + 1, 2 * q + 1
    ph = int(round(math.atan2(cq, ci) / (2 * math.pi) * 1024)) & 1023
    origin = 1 if (i in (-1, 0) and q in (-1, 0)) else 0
    rail = 1 if (i in (-8, 7) or q in (-8, 7)) else 0
    rows.append((w, ph, origin | (rail << 1), i, q))

out = os.path.join(os.path.dirname(__file__), "..", "src", "iq_phase_lut.v")
with open(out, "w") as f:
    f.write("// Generated by tools/gen_iq_lut.py - do not edit.\n")
    f.write("// 8-bit C5VRX IQ word (Q 3:0, I 7:4, signed 4-bit, cell centres 2k+1)\n")
    f.write("// -> phase (1024 per turn) and class {rail, origin}.\n")
    f.write("module iq_phase_lut (\n    input  wire       clk,\n    input  wire [7:0] w,\n")
    f.write("    output reg  [9:0] phase,\n    output reg  [1:0] cls\n);\n")
    f.write("    always @(posedge clk) begin\n        case (w)\n")
    for w, ph, c, i, q in rows:
        f.write(f"            8'd{w}: begin phase <= 10'd{ph}; cls <= 2'd{c}; end  // I={i} Q={q}\n")
    f.write("        endcase\n    end\nendmodule\n")
print("wrote", os.path.normpath(out))
