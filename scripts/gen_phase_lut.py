"""Generate src/phase_lut.vh: IQ byte -> phase, 1024 units per turn.

Byte layout (PARLIO data-bit order): Q = bits 3..0, I = bits 7..4, each a
4-bit two's complement value that stands for the ADC code range
[16k, 16k + 16), so its centre k + 0.5 is used for the angle.
"""
import math
import os


def phase(b):
    q, i = b & 15, b >> 4
    q = q - 16 if q & 8 else q
    i = i - 16 if i & 8 else i
    return int(round(math.atan2(q + 0.5, i + 0.5) / (2 * math.pi) * 1024)) & 1023


def main():
    out = os.path.join(os.path.dirname(__file__), "..", "src", "phase_lut.vh")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by scripts/gen_phase_lut.py: phase of an IQ byte, 1024 per turn.\n")
        f.write("function [9:0] phase_lut(input [7:0] b);\n    case (b)\n")
        for b in range(256):
            f.write(f"        8'h{b:02x}: phase_lut = 10'd{phase(b)};\n")
        f.write("    endcase\nendfunction\n")
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
