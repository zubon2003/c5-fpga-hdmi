"""Generate src/sincos_lut.vh: 256-step cos/sin, signed 8 bit (+-127),
and print the colour subcarrier NCO increment for the ~80 MHz symbols."""
import math
import os

FSC = 315e6 / 88          # NTSC colour subcarrier, 3.579545 MHz
FSYM = 80.0024e6          # C5 MODEM_DIAG symbol rate measured by the FPGA


def main():
    out = os.path.join(os.path.dirname(__file__), "..", "src", "sincos_lut.vh")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by scripts/gen_sincos_lut.py: cos / sin of a/256 turn, +-127.\n")
        f.write(f"localparam [31:0] SC_INC = 32'd{round(FSC / FSYM * 2**32)};   // {FSC:.2f} Hz at {FSYM:.0f} symbols/s\n")
        for name, fn in (("cos_lut", math.cos), ("sin_lut", math.sin)):
            f.write(f"function signed [7:0] {name}(input [7:0] a);\n    case (a)\n")
            for a in range(256):
                v = round(127 * fn(2 * math.pi * a / 256))
                f.write(f"        8'd{a}: {name} = {'-' if v < 0 else ''}8'sd{abs(v)};\n")
            f.write("    endcase\nendfunction\n")
    print("wrote", os.path.normpath(out), "SC_INC", round(FSC / FSYM * 2**32))


if __name__ == "__main__":
    main()
